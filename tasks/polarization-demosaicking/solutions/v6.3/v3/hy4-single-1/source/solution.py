_W = None


def _weights():
    global _W
    if _W is None:
        _W = tuple(np.frombuffer(base64.b64decode(b), dtype="<f4")
                   .reshape(DEG * F0, 16) for b in (_B64_A, _B64_B))
    return _W


def _lowpass3(a):
    """Separable [1,2,1]/4 smoothing, scipy-style 'reflect' boundaries."""
    p = np.pad(a, 1, mode="symmetric")
    b = 0.25 * (p[:-2, 1:-1] + p[2:, 1:-1]) + 0.5 * a
    p = np.pad(b, 1, mode="symmetric")
    return 0.25 * (p[1:-1, :-2] + p[1:-1, 2:]) + 0.5 * b


def _alignment_rho(raw):
    """Mean cross-phase high-frequency correlation: a registration cue."""
    r = raw.astype(np.float32)
    hp = []
    for a, b in PHASES:
        x = r[a::2, b::2]
        hp.append((x - _lowpass3(x)).ravel()[::7])
    s = 0.0
    for i in range(4):
        ai = hp[i]
        ai = ai - ai.mean()
        di = np.dot(ai, ai)
        for j in range(i + 1, 4):
            bj = hp[j]
            bj = bj - bj.mean()
            s += np.dot(ai, bj) / (np.sqrt(di * np.dot(bj, bj)) + 1e-6)
    rho = float(s / 6.0)
    return rho if np.isfinite(rho) else 0.3


def _features(raw):
    """(F0, N) contiguous rows: shifted phase sub-images, bias row last."""
    r = raw.astype(np.float32)
    h, w = r.shape
    nh, nw = h // 2, w // 2
    N = nh * nw
    x = r.copy()
    mu = np.empty(4, np.float32)
    for q, (a, b) in enumerate(PHASES):
        mu[q] = r[a::2, b::2].mean()
        x[a::2, b::2] -= mu[q]
    xp = [np.pad(x[a::2, b::2], P, mode="reflect") for a, b in PHASES]
    Xf = np.empty((F0, N), np.float32)
    k = 0
    for q in range(4):
        for du in range(-P, P + 1):
            for dv in range(-P, P + 1):
                Xf[k] = xp[q][P + du:P + du + nh, P + dv:P + dv + nw].reshape(-1)
                k += 1
    Xf[k] = 1.0
    return Xf, mu, nh, nw


def reconstruct(raw):
    raw = np.asarray(raw)
    orig_h, orig_w = raw.shape
    if orig_h % 2 or orig_w % 2:
        raw = np.pad(raw, ((0, orig_h % 2), (0, orig_w % 2)), mode="edge")
    WA, WB = _weights()
    rho = _alignment_rho(raw)
    r = np.float32(min(0.9, max(-0.3, rho)))
    t = np.float32(1.0 / (1.0 + np.exp((float(r) - 0.20) / 0.03)))
    WvA = WA.reshape(DEG, F0, 16)
    WvB = WB.reshape(DEG, F0, 16)
    Ea = WvA[0] + r * WvA[1] + (r * r) * WvA[2]
    Eb = WvB[0] + r * WvB[1] + (r * r) * WvB[2]
    We = ((1.0 - t) * Ea + t * Eb).astype(np.float32)
    Xf, mu, nh, nw = _features(raw)
    h, w = raw.shape
    Y = We.T @ Xf                    # (16, N) - one BLAS gemm
    out = np.empty((4, h, w), np.float32)
    for p, (a, b) in enumerate(PHASES):
        for c in range(4):
            out[c, a::2, b::2] = Y[p * 4 + c].reshape(nh, nw) + mu[QOFC[c]]
    for c, (a, b) in enumerate(CH_PHASE):
        out[c, a::2, b::2] = raw[a::2, b::2]
    if not np.isfinite(out).all():
        np.nan_to_num(out, copy=False, nan=128.0, posinf=255.0, neginf=0.0)
    np.clip(out, 0.0, 255.0, out=out)
    if orig_h == h and orig_w == w:
        return out
    return out[:, :orig_h, :orig_w].copy()
