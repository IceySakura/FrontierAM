def _load():
    path = os.path.join(_DIR, 'model.npz')
    src = path if os.path.exists(path) else io.BytesIO(base64.b64decode(_WEIGHTS))
    f = {k: v.astype(np.float64) for k, v in np.load(src).items()}
    kn2 = f['lin_r.weight'].shape[1]
    W1 = f['f1.weight']
    H1 = W1.shape[0]
    A = np.zeros((48 + H1, kn2 + 2))
    A[:48, :kn2] = f['lin_r.weight']
    A[48:, :kn2] = W1[:, :kn2]
    A[48:, kn2] = W1[:, kn2]
    A[48:, kn2 + 1] = f['f1.bias'] - W1[:, :kn2].sum(1) - 4.0 * W1[:, kn2]
    D = np.concatenate([f['lin_d.weight'], f['lin_d.bias'][:, None]], 1)
    W2 = np.concatenate([f['f2.weight'], f['f2.bias'][:, None]], 1)
    W3 = np.concatenate([f['f3.weight'], f['f3.bias'][:, None]], 1)
    c = lambda x: np.ascontiguousarray(x, dtype=np.float32)
    kn = int(round(np.sqrt(kn2 // 4)))
    ctx = kn2 - kn * kn * 4                   # 8 -> box-mean context features (scales 5 and 9)
    kd = int(round(np.sqrt((D.shape[1] - 1) // 4)))
    return c(A), c(D), c(W2), c(W3), H1, kn, kd, ctx


_A, _D, _W2, _W3, _H1, _KN, _KD, _CTX = _load()
_USE_D = bool(np.any(_D[:, :-1] != 0))   # linear raw-patch term present?
_PAD = 2 * (max(_KN, _KD if _USE_D else 1) // 2) + 2   # even, >= superpixel radius + 1 px for L


def _cols(img, h, w, k, extra):
    """im2col of k x k super-pixels around each super-pixel: returns (k*k*4+extra, h*w)."""
    ps = _PAD // 2
    P = img.reshape(h + 2 * ps, 2, w + 2 * ps, 2).transpose(1, 3, 0, 2)
    o = ps - k // 2
    X = np.empty((k * k * 4 + extra, h * w), np.float32)
    Xv = X[:k * k * 4].reshape(k, k, 2, 2, h, w)
    for a in range(k):
        for b in range(k):
            Xv[a, b] = P[:, :, o + a:o + a + h, o + b:o + b + w]
    return X


def _box59(img4):
    """5x5 and 9x9 box means (edge replication) of a (4, h, w) array, separable sums."""
    h, w = img4.shape[1:]
    x = np.pad(img4, ((0, 0), (4, 4), (4, 4)), mode='edge')
    t5 = x[:, :, 2:2 + w] + x[:, :, 3:3 + w]
    t5 += x[:, :, 4:4 + w]
    t5 += x[:, :, 5:5 + w]
    t5 += x[:, :, 6:6 + w]
    t9 = t5 + x[:, :, 0:w]
    t9 += x[:, :, 1:1 + w]
    t9 += x[:, :, 7:7 + w]
    t9 += x[:, :, 8:8 + w]
    o5 = t5[:, 2:2 + h] + t5[:, 3:3 + h]
    o5 += t5[:, 4:4 + h]
    o5 += t5[:, 5:5 + h]
    o5 += t5[:, 6:6 + h]
    o9 = t9[:, 2:2 + h] + t9[:, 3:3 + h]
    o9 += t9[:, 4:4 + h]
    o9 += t9[:, 5:5 + h]
    o9 += t9[:, 6:6 + h]
    o9 += t9[:, 0:h]
    o9 += t9[:, 1:1 + h]
    o9 += t9[:, 7:7 + h]
    o9 += t9[:, 8:8 + h]
    o5 *= np.float32(1 / 25)
    o9 *= np.float32(1 / 81)
    return o5, o9


def reconstruct(raw):
    raw = np.asarray(raw)
    H0, W0 = raw.shape
    r = raw.astype(np.float32)
    H, W = H0 + (H0 & 1), W0 + (W0 & 1)
    if (H, W) != (H0, W0):
        r = np.pad(r, ((0, H - H0), (0, W - W0)), mode='symmetric')
    h, w = H // 2, W // 2
    N = h * w
    pad = _PAD
    rp = np.pad(r, pad, mode='reflect')
    # 3x3 binomial local intensity (weights the four angles equally), on the padded grid
    a = rp[:-2] + rp[2:]
    a += rp[1:-1]
    a += rp[1:-1]
    Lc = a[:, :-2] + a[:, 2:]
    Lc += a[:, 1:-1]
    Lc += a[:, 1:-1]
    Lc *= np.float32(1 / 16)                     # (H+2pad-2, W+2pad-2) = L on grid padded by pad-1
    L = Lc[pad - 1:pad - 1 + H, pad - 1:pad - 1 + W]
    Lpad = np.pad(L, pad, mode='reflect')
    Lpad += np.float32(1.0)
    n = np.divide(rp, Lpad, out=Lpad)
    Lq = L.reshape(h, 2, w, 2).transpose(1, 3, 0, 2).reshape(4, N)
    Lbar = Lq.sum(0)
    Lbar *= np.float32(0.25)

    if _USE_D:
        Xd = _cols(rp, h, w, _KD, 1)
        Xd[-1] = 1.0
    Xn = _cols(n, h, w, _KN, 2 + _CTX)
    if _CTX:
        k2 = _KN * _KN * 4
        nsp = n[pad:pad + H, pad:pad + W].reshape(h, 2, w, 2).transpose(1, 3, 0, 2).reshape(4, h, w)
        b5, b9 = _box59(nsp)
        Xn[k2:k2 + 4] = b5.reshape(4, N)
        Xn[k2 + 4:k2 + 8] = b9.reshape(4, N)
    np.log(Lbar + np.float32(1.0), out=Xn[-2])
    Xn[-1] = 1.0
    del n, rp, a, Lc

    Z = _A @ Xn                                   # (48 + H1, N): ratio term and first MLP layer
    del Xn
    if _USE_D:
        Y = _D @ Xd                               # (12, N) linear "difference" term
        del Xd
        Y += Z[0:12] * Lq[0]
    else:
        Y = Z[0:12] * Lq[0]
        Y += _D[:, -1:]
    for q in range(1, 4):
        Y += Z[12 * q:12 * q + 12] * Lq[q]
    Hh = np.empty((_H1 + 1, N), np.float32)
    np.maximum(Z[48:], 0, out=Hh[:_H1])
    Hh[_H1] = 1.0
    del Z
    H2 = _W2 @ Hh
    del Hh
    H2b = np.empty((H2.shape[0] + 1, N), np.float32)
    np.maximum(H2, 0, out=H2b[:-1])
    H2b[-1] = 1.0
    del H2
    R = _W3 @ H2b
    del H2b
    R *= Lbar
    Y += R
    np.clip(Y, 0, 255, out=Y)

    out = np.empty((4, H, W), np.float32)
    Yr = Y.reshape(12, h, w)
    for i, (q, c) in enumerate(_UNOBS):
        out[c, q >> 1::2, q & 1::2] = Yr[i]
    for q in range(4):
        out[_OBS[q], q >> 1::2, q & 1::2] = r[q >> 1::2, q & 1::2]
    if (H, W) != (H0, W0):
        out = np.ascontiguousarray(out[:, :H0, :W0])
    return out
