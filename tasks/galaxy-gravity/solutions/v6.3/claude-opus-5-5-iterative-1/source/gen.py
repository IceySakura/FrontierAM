# generate straight-line SIMD derivative code for Plummer kernel, orders p in PLIST
import sys
import os
PLIST = [int(v) for v in os.environ.get("PLIST","8 10 12").split()]
out = []
out.append('// generated by gen.py')
for p in PLIST:
    # multi-index ordering identical to Tables::init
    idx = {}
    order = []
    for n in range(p + 1):
        for a in range(n, -1, -1):
            for b in range(n - a, -1, -1):
                c = n - a - b
                idx[(a, b, c)] = len(order)
                order.append((a, b, c))
    nc = len(order)
    # R entries: (k, m) for m <= p - deg(k); offsets m-minor
    roff = []
    tot = 0
    for (a, b, c) in order:
        roff.append(tot)
        tot += p - (a + b + c) + 1
    out.append(f'static void derivs4_p{p}(__m256d x, __m256d y, __m256d z, __m256d* __restrict D, __m256d* __restrict R) {{')
    out.append('    __m256d u = _mm256_add_pd(_mm256_fmadd_pd(x, x, _mm256_fmadd_pd(y, y, _mm256_mul_pd(z, z))), _mm256_set1_pd(EPS2));')
    out.append('    __m256d s = _mm256_div_pd(_mm256_set1_pd(1.0), _mm256_sqrt_pd(u));')
    out.append('    __m256d iu = _mm256_mul_pd(s, s);')
    out.append('    R[0] = s;')
    for m in range(1, p + 1):
        out.append(f'    R[{m}] = _mm256_mul_pd(R[{m-1}], _mm256_mul_pd(_mm256_set1_pd({-(2.0*(m-1)+1)}), iu));')
    out.append('    D[0] = R[0];')
    for k in range(1, nc):
        a, b, c = order[k]
        n = a + b + c
        if a > 0:
            w = 'x'; k1 = idx[(a-1, b, c)]; k2 = idx[(a-2, b, c)] if a >= 2 else -1; cf = a - 1
        elif b > 0:
            w = 'y'; k1 = idx[(a, b-1, c)]; k2 = idx[(a, b-2, c)] if b >= 2 else -1; cf = b - 1
        else:
            w = 'z'; k1 = idx[(a, b, c-1)]; k2 = idx[(a, b, c-2)] if c >= 2 else -1; cf = c - 1
        for m in range(0, p - n + 1):
            dst = roff[k] + m
            s1 = roff[k1] + m + 1
            if k2 >= 0:
                s2 = roff[k2] + m + 1
                if cf == 1:
                    out.append(f'    R[{dst}] = _mm256_fmadd_pd({w}, R[{s1}], R[{s2}]);')
                else:
                    out.append(f'    R[{dst}] = _mm256_fmadd_pd({w}, R[{s1}], _mm256_mul_pd(_mm256_set1_pd({float(cf)}), R[{s2}]));')
            else:
                out.append(f'    R[{dst}] = _mm256_mul_pd({w}, R[{s1}]);')
        out.append(f'    D[{k}] = R[{roff[k]}];')
    out.append('}')
out.append('typedef void (*derivs4_fn)(__m256d, __m256d, __m256d, __m256d*, __m256d*);')
out.append('static derivs4_fn derivs4_table(int p) {')
out.append('    switch (p) {')
for p in PLIST:
    out.append(f'    case {p}: return derivs4_p{p};')
out.append('    default: return nullptr;')
out.append('    }')
out.append('}')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
