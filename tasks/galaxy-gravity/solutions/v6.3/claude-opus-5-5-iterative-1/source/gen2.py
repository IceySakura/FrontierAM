# generate Taylor-coefficient recursion derivs: D_k = k! T_k, with
# T_k = -[(2n-1) sum_i x_i T_{k-e_i} + (n-1) sum_i T_{k-2e_i}] / (n u)
import sys, os, math
PLIST = [int(v) for v in os.environ.get("PLIST", "8 10 12").split()]
out = ['// generated by gen2.py']
DENSE = os.environ.get('DENSE') == '1'
for p in PLIST:
    idx = {}; order = []
    for n in range(p + 1):
        for a in range(n, -1, -1):
            for b in range(n - a, -1, -1):
                c = n - a - b; idx[(a, b, c)] = len(order); order.append((a, b, c))
    nc = len(order)
    S1 = (p + 1) * (p + 1); S2 = p + 1
    def dn(k):
        a, b, c = order[k]
        return a * S1 + b * S2 + c if DENSE else k
    fname = 'derivs4d_p' if DENSE else 'derivs4t_p'
    out.append(f'static void {fname}{p}(__m256d x, __m256d y, __m256d z, __m256d* __restrict D, __m256d* __restrict Tm) {{')
    out.append('    __m256d u = _mm256_add_pd(_mm256_fmadd_pd(x, x, _mm256_fmadd_pd(y, y, _mm256_mul_pd(z, z))), _mm256_set1_pd(EPS2));')
    out.append('    __m256d iu = _mm256_div_pd(_mm256_set1_pd(1.0), u);')
    out.append('    __m256d s = _mm256_sqrt_pd(iu);')
    out.append('    Tm[0] = s; D[0] = s;')
    for n in range(1, p + 1):
        out.append(f'    {{ const __m256d c1 = _mm256_mul_pd(_mm256_set1_pd({-(2.0*n-1)/n!r}), iu), c2 = _mm256_mul_pd(_mm256_set1_pd({-(n-1.0)/n!r}), iu);')
        for (a, b, c) in [o for o in order if sum(o) == n]:
            k = idx[(a, b, c)]
            t1 = []
            if a >= 1: t1.append(('x', idx[(a-1, b, c)]))
            if b >= 1: t1.append(('y', idx[(a, b-1, c)]))
            if c >= 1: t1.append(('z', idx[(a, b, c-1)]))
            t2 = []
            if a >= 2: t2.append(idx[(a-2, b, c)])
            if b >= 2: t2.append(idx[(a, b-2, c)])
            if c >= 2: t2.append(idx[(a, b, c-2)])
            e1 = f'_mm256_mul_pd({t1[0][0]}, Tm[{t1[0][1]}])'
            for w, j in t1[1:]:
                e1 = f'_mm256_fmadd_pd({w}, Tm[{j}], {e1})'
            if t2:
                e2 = f'Tm[{t2[0]}]'
                for j in t2[1:]:
                    e2 = f'_mm256_add_pd({e2}, Tm[{j}])'
                expr = f'_mm256_fmadd_pd(c1, {e1}, _mm256_mul_pd(c2, {e2}))'
            else:
                expr = f'_mm256_mul_pd(c1, {e1})'
            f = math.factorial(a) * math.factorial(b) * math.factorial(c)
            out.append(f'      {{ __m256d t = {expr}; Tm[{k}] = t; D[{dn(k)}] = _mm256_mul_pd(t, _mm256_set1_pd({float(f)!r})); }}')
        out.append('    }')
    out.append('}')
out.append('static derivs4_fn derivs4d_table(int p) {' if DENSE else 'static derivs4_fn derivs4t_table(int p) {')
out.append('    switch (p) {')
for p in PLIST:
    out.append(f'    case {p}: return derivs4d_p{p};' if DENSE else f'    case {p}: return derivs4t_p{p};')
out.append('    default: return nullptr;')
out.append('    }')
out.append('}')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
