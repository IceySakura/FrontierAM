#!/usr/bin/env python3
"""Emit straight-line Taylor coefficient recurrences for the offline build."""
import math
from pathlib import Path

maximum = 20
terms = []
indices = {}
for degree in range(maximum + 1):
    for x in range(degree + 1):
        for y in range(degree - x + 1):
            t = (x, y, degree-x-y)
            indices[t] = len(terms)
            terms.append(t)

lines = ["// Generated by generate_kernels.py.\n"]
for variant in ("scalar", "vector", "harmonic"):
    vector = variant != "scalar"
    typ = "__m256d" if vector else "double"
    name = {"scalar": "kernel_scalar", "vector": "kernel4", "harmonic": "kernel_harmonic4"}[variant]
    lines.append(f"__attribute__((noinline)) static void {name}"
                 f"(int p, {typ} ux, {typ} uy, {typ} uz, {typ} *out) {{")
    lines.append(f"    {typ} c[CMAX];")
    one = "_mm256_set1_pd(1.0)" if vector else "1.0"
    lines.append(f"    c[0] = out[0] = {one};")
    for degree in range(1, maximum + 1):
        lines.append(f"    if (p < {degree}) return;")
        for t in terms:
            if sum(t) != degree:
                continue
            if variant == "harmonic" and t[2] > 1:
                continue
            i = indices[t]
            linear = []
            square = []
            for axis, u in enumerate(("ux", "uy", "uz")):
                prev = list(t)
                if t[axis]:
                    prev[axis] -= 1
                    j = indices[tuple(prev)]
                    linear.append(f"_mm256_mul_pd({u}, c[{j}])" if vector else f"{u}*c[{j}]")
                if t[axis] > 1:
                    prev[axis] -= 1
                    square.append(f"c[{indices[tuple(prev)]}]")
            def add(items):
                if not items:
                    return "_mm256_setzero_pd()" if vector else "0.0"
                expr = items[0]
                for item in items[1:]:
                    expr = f"_mm256_add_pd({expr}, {item})" if vector else f"({expr}+{item})"
                return expr
            f1 = repr(-(2*degree-1)/degree)
            f2 = repr(-(degree-1)/degree)
            if vector:
                expr = f"_mm256_mul_pd(_mm256_set1_pd({f1}), {add(linear)})"
                if square:
                    expr = (f"_mm256_fmadd_pd(_mm256_set1_pd({f1}), {add(linear)}, "
                            f"_mm256_mul_pd(_mm256_set1_pd({f2}), {add(square)}))")
            else:
                expr = f"{f1}*({add(linear)})"
                if square:
                    expr += f" + {f2}*({add(square)})"
            lines.append(f"    c[{i}] = {expr};")
            factorial = math.prod(math.factorial(v) for v in t)
            expr = (f"_mm256_mul_pd(c[{i}], _mm256_set1_pd({float(factorial)}))"
                    if vector else f"c[{i}]*{float(factorial)}")
            lines.append(f"    out[{i}] = {expr};")
    lines.append("}\n")
Path(__file__).with_name("kernels.inc").write_text("\n".join(lines) + "\n")
