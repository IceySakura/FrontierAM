#!/usr/bin/env python3
"""Generate the fixed-order Cartesian translations used by the solver."""
from pathlib import Path
import math


def indices(p):
    return [(x, y, d-x-y)
            for d in range(p+1) for x in range(d, -1, -1)
            for y in range(d-x, -1, -1)]


def generate(p):
    idx = indices(p)
    lookup = {v: i for i, v in enumerate(idx)}
    nm = len(indices(p-1))
    out = [
        f"template<> struct Kernel<{p}> {{",
        f"static constexpr int P={p}, NC={len(idx)}, NM={nm};",
        f"static constexpr int TERMS={math.comb(p+6,6)-math.comb(p+3,3)-3*(math.comb(p+2,3)-1)};",
        "static constexpr int powers[NC][3] = {",
        ",".join("{%d,%d,%d}" % a for a in idx), "};",
        "static void derivatives(V x,V y,V z,V inv,V d[NC]) {",
        "d[0]=vsqrt(inv);",
    ]
    xyz = ["x", "y", "z"]
    for k, a in enumerate(idx[1:], 1):
        axis = max(range(3), key=lambda i: a[i])
        terms = []
        for j in range(3):
            if not a[j]:
                continue
            b = list(a)
            b[j] -= 1
            c = (2*a[j]-1) if j == axis else (2*a[j])
            terms.append(f"V({c}.0)*{xyz[j]}*d[{lookup[tuple(b)]}]")
            if a[j] >= 2:
                b[j] -= 1
                c = (a[j]-1)**2 if j == axis else a[j]*(a[j]-1)
                terms.append(f"V({c}.0)*d[{lookup[tuple(b)]}]")
        out.append(f"d[{k}]=-inv*({' + '.join(terms)});")
    out += ["}", "static void translate(const V* ma,const V* mb,const V* d,V* la,V* lb) {"]
    for ib, b in enumerate(idx[1:], 1):
        aa, bb = [], []
        for ia, a in enumerate(idx[:nm]):
            if sum(a)+sum(b) > p:
                break
            if sum(a) == 1:
                continue
            ab = tuple(a[i]+b[i] for i in range(3))
            di = lookup[ab]
            aa.append(("-" if sum(a) % 2 else "+") + f"mb[{ia}]*d[{di}]")
            bb.append("+" + f"ma[{ia}]*d[{di}]")
        def dot(terms):
            groups = ["(" + "".join(terms[j::4]).lstrip("+") + ")"
                      for j in range(min(4,len(terms)))]
            return "+".join(groups)
        out.append(f"la[{ib}]=" + dot(aa) + ";")
        out.append(f"lb[{ib}]=" + ("-(" if sum(b) % 2 else "(")
                   + dot(bb) + ");")
    out += ["}", "static void evaluate(const double* m,const V* d,V& fx,V& fy,V& fz) {"]
    for j, name in enumerate(["fx", "fy", "fz"]):
        terms = []
        for ia, a in enumerate(idx[:nm]):
            if sum(a) == 1:
                continue
            b = list(a)
            b[j] += 1
            di = lookup[tuple(b)]
            terms.append(("-" if sum(a) % 2 else "+") + f"V(m[{ia}])*d[{di}]")
        out.append(f"{name}+=" + dot(terms) + ";")
    out += ["}", "static void monomials(V x,V y,V z,V* h) {", "h[0]=V(1.);"]
    for i,a in enumerate(idx[1:nm],1):
        axis=next(j for j in range(3) if a[j])
        b=list(a); b[axis]-=1
        out.append(f"h[{i}]=h[{lookup[tuple(b)]}]*{xyz[axis]}"+
                   (f"*V({1/a[axis]:.17g})" if a[axis]>1 else "")+";")
    out += ["}", "static void local_evaluate(const double* l,const V* t,V& fx,V& fy,V& fz) {"]
    for j,name in enumerate(["fx","fy","fz"]):
        terms=[]
        for ia,a in enumerate(idx[:nm]):
            b=list(a); b[j]+=1
            terms.append(f"+t[{ia}]*V(l[{lookup[tuple(b)]}])")
        out.append(f"{name}+="+dot(terms)+";")
    out += ["}", "};"]
    return "\n".join(out)


Path(__file__).with_name("kernels.hpp").write_text(
    "// Generated by generate.py.\n" +
    "\n".join(generate(p) for p in [4, 6, 8, 10, 12]))
