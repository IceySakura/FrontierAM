#!/usr/bin/env python3
"""Generate straight-line Cartesian M2L kernels for selected (P,Q)."""
import itertools, sys

COMBOS = [(2,2)]

def mi(N):
    out=[]
    for n in range(N+1):
        for a in range(n+1):
            for b in range(n-a+1):
                c=n-a-b
                out.append((a,b,c,n))
    return out

def build(P,Q):
    N=P+Q
    allmi=mi(N)
    gidx={e:k for k,e in enumerate(allmi)}
    midx={e:k for k,e in enumerate(allmi) if e[3]<=P}
    widx={e:k for k,e in enumerate(allmi) if e[3]<=Q}
    KG=len(allmi); KP=len(midx); KQ=len(widx)
    def g3(a,b,c): return gidx[(a,b,c,a+b+c)]
    lines=[]
    lines.append(f"/* P={P} Q={Q} KG={KG} KP={KP} KQ={KQ} */")
    # ---- derivative tensor ----
    lines.append(f"static inline void g_{P}_{Q}(const double *__restrict dh, double *__restrict G) {{")
    lines.append("  const double d0=dh[0], d1=dh[1], d2=dh[2];")
    lines.append("  G[0]=1.0;")
    for (a,b,c,n) in allmi:
        if n==0: continue
        v=[a,b,c]
        ii=0 if v[0]>0 else (1 if v[1]>0 else 2)
        al=v[:]; al[ii]-=1
        # terms: (slot, coeff, dh index or -1)
        terms=[]
        terms.append([g3(*al),1.0,ii])
        if al[ii]>0:
            t=al[:]; t[ii]-=1
            terms.append([g3(*t),float(al[ii]),-1])
        for j in range(3):
            if al[j]>0:
                t=al[:]; t[j]-=1; t[ii]+=1
                terms.append([g3(*t),2.0*al[j],j])
        for j in range(3):
            if al[j]>1:
                t=al[:]; t[j]-=2; t[ii]+=1
                terms.append([g3(*t),float(al[j]*(al[j]-1)),-1])
        # combine terms with identical (slot, dh)
        comb={}
        for s,co,dj in terms:
            comb[(s,dj)]=comb.get((s,dj),0.0)+co
        parts=[]
        for (s,dj),co in sorted(comb.items()):
            if co==0: continue
            cs = "" if abs(co-1.0)<1e-14 else (f"{co:.1f}*")
            if dj>=0:
                parts.append(f"{cs}d{dj}*G[{s}]")
            else:
                parts.append(f"{cs}G[{s}]")
        body=" + ".join(parts) if parts else "0.0"
        lines.append(f"  G[{g3(a,b,c)}] = -({body});")
    lines.append("}")
    # ---- contraction: T[gamma] = sum_alpha msc[alpha]*G[alpha+gamma] ----
    lines.append(f"static inline void c_{P}_{Q}(const double *__restrict msc, const double *__restrict G, double *__restrict T) {{")
    for w in range(KQ):
        lines.append(f"  T[{w}]=0.0;")
    for e,m in midx.items():
        a,b,c,n=e
        lines.append(f"  {{ const double m = msc[{m}];")
        for f,w in widx.items():
            ga,gb,gc,_=f
            lines.append(f"    T[{w}] += m*G[{g3(a+ga,b+gb,c+gc)}];")
        lines.append("  }")
    lines.append("}")
    return lines, KP, KQ, KG

out=[]
out.append("// Generated by gen.py -- do not edit.")
out.append("#ifndef M2L_GEN_H")
out.append("#define M2L_GEN_H")
out.append("typedef void (*gfunc_t)(const double*, double*);")
out.append("typedef void (*cfunc_t)(const double*, const double*, double*);")
registry={}
for P,Q in COMBOS:
    ls,KP,KQ,KG=build(P,Q)
    out+=ls
    registry[(P,Q)]=(KP,KQ,KG)
out.append("static inline gfunc_t get_gfunc(int P,int Q){")
for (P,Q) in COMBOS:
    out.append(f"  if(P=={P}&&Q=={Q}) return g_{P}_{Q};")
out.append("  return 0; }")
out.append("static inline cfunc_t get_cfunc(int P,int Q){")
for (P,Q) in COMBOS:
    out.append(f"  if(P=={P}&&Q=={Q}) return c_{P}_{Q};")
out.append("  return 0; }")
out.append("#endif")
open(sys.argv[1] if len(sys.argv)>1 else 'm2l_gen.h','w').write("\n".join(out)+"\n")
print("generated", len(out), "lines", file=sys.stderr)
