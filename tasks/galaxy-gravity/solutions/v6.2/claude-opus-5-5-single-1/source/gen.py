#!/usr/bin/env python3
"""Generate unrolled Cartesian FMM kernels (softened kernel) for expansion order P.

Output: kern_p{P}.h defining
  P_ORDER, NCOEF, NCOEF_PAD
  derivs(X,Y,Z,eps2,D)   : D[idx(t,u,v)] = d^t_x d^u_y d^v_z (|R|^2+eps2)^(-1/2), 4 lanes
  m2l_contract(M,D,L)    : L[l] += sum_{|k|<=P-|l|, |k|!=1} M[k] * D[k+l], 4 lanes
"""
import sys


def indices(P):
    idx = []
    for n in range(P + 1):
        for t in range(n, -1, -1):
            for u in range(n - t, -1, -1):
                idx.append((t, u, n - t - u))
    return idx



def gen_m2l_blocked(P, idx, pos, b=4, name="m2l_contract"):
    o = []
    o.append("static inline void %s(const v4d* __restrict M, const v4d* __restrict D, v4d* __restrict L) {" % name)
    for ly in range(P + 1):
        for lz in range(P + 1 - ly):
            maxlx = P - ly - lz
            for l0 in range(0, maxlx + 1, b):
                blk = list(range(l0, min(l0 + b, maxlx + 1)))
                o.append("  {")
                for j, lx in enumerate(blk):
                    o.append("    v4d a%d = L[%d];" % (j, pos[(lx, ly, lz)]))
                for ky in range(P + 1):
                    for kz in range(P + 1 - ky):
                        Q = P - (ky + kz + ly + lz)
                        if Q < l0:
                            continue
                        body = []
                        loaded = set()
                        for kx in range(0, Q - l0 + 1):
                            if kx + ky + kz == 1:
                                continue
                            terms = [(j, kx + lx) for j, lx in enumerate(blk) if kx + lx <= Q]
                            if not terms:
                                continue
                            body.append("      { v4d mk = M[%d];" % pos[(kx, ky, kz)])
                            for j, nx in terms:
                                if nx not in loaded:
                                    body.append("        d%d = D[%d];" % (nx, pos[(nx, ky + ly, kz + lz)]))
                                    loaded.add(nx)
                                body.append("        a%d += mk*d%d;" % (j, nx))
                            body.append("      }")
                        if not body:
                            continue
                        o.append("    { v4d %s;" % ", ".join("d%d" % n for n in sorted(loaded)))
                        o.extend(body)
                        o.append("    BARRIER(); }")
                for j, lx in enumerate(blk):
                    o.append("    L[%d] = a%d;" % (pos[(lx, ly, lz)], j))
                o.append("  }")
    o.append("}")
    return o


def gen(P, G=8, B=4):
    idx = indices(P)
    pos = {m: i for i, m in enumerate(idx)}
    nc = len(idx)
    ncp = (nc + 3) // 4 * 4
    o = []
    o.append("// generated by gen.py, P=%d" % P)
    o.append("#pragma once")
    o.append("#define P_ORDER %d" % P)
    o.append("#define NCOEF %d" % nc)
    o.append("#define NCOEF_PAD %d" % ncp)
    o.append('#ifndef BARRIER\n#define BARRIER() asm volatile("" ::: "memory")\n#endif')
    # index table
    o.append("static const int IDX_T[NCOEF] = {%s};" % ",".join(str(m[0]) for m in idx))
    o.append("static const int IDX_U[NCOEF] = {%s};" % ",".join(str(m[1]) for m in idx))
    o.append("static const int IDX_V[NCOEF] = {%s};" % ",".join(str(m[2]) for m in idx))

    # ---------------- derivs ----------------
    def derivs(PP, name):
        idxp = indices(PP)
        o.append("static inline void %s(v4d X, v4d Y, v4d Z, double eps2, v4d* __restrict D) {" % name)
        o.append("  v4d s = X*X + Y*Y + Z*Z + eps2;")
        o.append("  v4d g0 = 1.0 / _mm256_sqrt_pd(s);")
        o.append("  v4d q = g0*g0;")

        def nm(m, t, u, v):
            return "r%d_%d_%d_%d" % (m, t, u, v)

        o.append("  v4d %s = g0;" % nm(0, 0, 0, 0))
        for m in range(1, PP + 1):
            o.append("  v4d %s = %s * (q * %.1f);" % (nm(m, 0, 0, 0), nm(m - 1, 0, 0, 0), -(2 * m - 1)))
        for d in range(1, PP + 1):
            for m in range(0, PP - d + 1):
                for t in range(d, -1, -1):
                    for u in range(d - t, -1, -1):
                        v = d - t - u
                        if t > 0:
                            a = nm(m + 1, t - 1, u, v)
                            b = nm(m + 1, t - 2, u, v) if t >= 2 else None
                            c = t - 1
                            var = "X"
                        elif u > 0:
                            a = nm(m + 1, t, u - 1, v)
                            b = nm(m + 1, t, u - 2, v) if u >= 2 else None
                            c = u - 1
                            var = "Y"
                        else:
                            a = nm(m + 1, t, u, v - 1)
                            b = nm(m + 1, t, u, v - 2) if v >= 2 else None
                            c = v - 1
                            var = "Z"
                        if b is not None and c > 0:
                            o.append("  v4d %s = %s*%s + %s*%.1f;" % (nm(m, t, u, v), var, a, b, float(c)))
                        else:
                            o.append("  v4d %s = %s*%s;" % (nm(m, t, u, v), var, a))
        for i, (t, u, v) in enumerate(idxp):
            o.append("  D[%d] = %s;" % (i, nm(0, t, u, v)))
        o.append("}")

    derivs(P, "derivs")
    derivs(P + 1, "derivs_p1")
    idx1 = indices(P + 1)
    pos1 = {m: i for i, m in enumerate(idx1)}
    o.append("#define NCOEF1 %d" % len(idx1))
    o.append("#define NCOEF1_PAD %d" % ((len(idx1) + 3) // 4 * 4))
    # m2p: a += grad of potential: a_x = sum_k M_k D1[k+ex]
    o.append("static inline void m2p_contract(const v4d* __restrict M, const v4d* __restrict D, v4d& AX, v4d& AY, v4d& AZ) {")
    o.append("  v4d ax0 = AX, ay0 = AY, az0 = AZ, ax1 = {0,0,0,0}, ay1 = ax1, az1 = ax1;")
    kk = [i for i in range(nc) if sum(idx[i]) != 1]
    for n, k in enumerate(kk):
        t, u, v = idx[k]
        sfx = n & 1
        o.append("  { v4d mk = M[%d]; ax%d += mk*D[%d]; ay%d += mk*D[%d]; az%d += mk*D[%d]; }" % (
            k, sfx, pos1[(t + 1, u, v)], sfx, pos1[(t, u + 1, v)], sfx, pos1[(t, u, v + 1)]))
    o.append("  AX = ax0 + ax1; AY = ay0 + ay1; AZ = az0 + az1;")
    o.append("}")


    # ---------------- P2M (4 particles per call): acc[k] += m * w^k/k!, w = centre - x ----------------
    o.append("static inline void p2m4(v4d wx, v4d wy, v4d wz, v4d m, v4d* __restrict acc) {")
    for c, w in (("x", "wx"), ("y", "wy")):
        o.append("  v4d p%s0 = {1.0,1.0,1.0,1.0};" % c)
        for t in range(1, P + 1):
            o.append("  v4d p%s%d = p%s%d * %s * %.17g;" % (c, t, c, t - 1, w, 1.0 / t))
    o.append("  v4d pz0 = m;")
    for t in range(1, P + 1):
        o.append("  v4d pz%d = pz%d * wz * %.17g;" % (t, t - 1, 1.0 / t))
    for u in range(P + 1):
        for v in range(P + 1 - u):
            o.append("  v4d yz%d_%d = py%d * pz%d;" % (u, v, u, v))
    for i, (t, u, v) in enumerate(idx):
        o.append("  acc[%d] += px%d * yz%d_%d;" % (i, t, u, v))
    o.append("}")

    # ---------------- L2P (4 particles per call) ----------------
    o.append("static inline void l2p4(const double* __restrict L, v4d vx, v4d vy, v4d vz, v4d& AX, v4d& AY, v4d& AZ) {")
    for c, w in (("x", "vx"), ("y", "vy"), ("z", "vz")):
        o.append("  v4d p%s0 = {1.0,1.0,1.0,1.0};" % c)
        for t in range(1, P):
            o.append("  v4d p%s%d = p%s%d * %s * %.17g;" % (c, t, c, t - 1, w, 1.0 / t))
    o.append("  v4d ax = {0,0,0,0}, ay = ax, az = ax;")
    for u in range(P):
        for v in range(P - u):
            o.append("  { v4d yz = py%d * pz%d;" % (u, v))
            for t in range(P - u - v):
                o.append("    { v4d mo = px%d * yz; ax += mo * L[%d]; ay += mo * L[%d]; az += mo * L[%d]; }" % (
                    t, pos[(t + 1, u, v)], pos[(t, u + 1, v)], pos[(t, u, v + 1)]))
            o.append("  }")
    o.append("  AX += ax; AY += ay; AZ += az;")
    o.append("}")

    # ---------------- M2M: Mp[k] += sum_{j<=k} Mc[j] e^(k-j)/(k-j)!  (separable, e = parent - child) ----------------
    def sep(name, src, dst, up):
        o.append("static inline void %s(const double* __restrict %s, const double* __restrict ex, const double* __restrict ey, const double* __restrict ez, double* __restrict %s) {" % (name, src, dst))
        o.append("  double A[NCOEF], B[NCOEF];")
        for stage, (inp, outp, e) in enumerate(((src, "A", "ex"), ("A", "B", "ey"), ("B", dst, "ez"))):
            for i, (t, u, v) in enumerate(idx):
                c = [t, u, v][stage]
                terms = []
                if up:   # sum over c' <= c
                    for cp in range(0, c + 1):
                        m = [t, u, v]; m[stage] = cp
                        terms.append((pos[tuple(m)], c - cp))
                else:    # sum over c' >= c with total degree <= P
                    rest = t + u + v - c
                    for cp in range(c, P - rest + 1):
                        m = [t, u, v]; m[stage] = cp
                        terms.append((pos[tuple(m)], cp - c))
                expr = " + ".join(("%s[%d]" % (inp, j)) if k == 0 else ("%s[%d]*%s[%d]" % (inp, j, e, k)) for j, k in terms)
                if stage < 2:
                    o.append("  %s[%d] = %s;" % (outp, i, expr))
                else:
                    o.append("  %s[%d] += %s;" % (outp, i, expr))
        o.append("}")
    sep("m2m_gen", "Mc", "Mp", True)
    sep("l2l_gen", "Lp", "Lc", False)

    # ---------------- m2l contraction ----------------
    o.append("static inline void m2l_contract(const v4d* __restrict M, const v4d* __restrict D, v4d* __restrict L) {")
    ls = list(range(nc))  # ordered by degree
    ks = [i for i in range(nc) if sum(idx[i]) != 1]
    for g0 in range(0, nc, G):
        grp = ls[g0:g0 + G]
        o.append("  {")
        for j, l in enumerate(grp):
            o.append("    v4d a%d = L[%d];" % (j, l))
        minl = min(sum(idx[l]) for l in grp)
        for k in ks:
            nk = sum(idx[k])
            if nk + minl > P:
                continue
            o.append("    { v4d mk = M[%d];" % k)
            for j, l in enumerate(grp):
                if nk + sum(idx[l]) <= P:
                    kl = tuple(a + b for a, b in zip(idx[k], idx[l]))
                    o.append("      a%d += mk*D[%d];" % (j, pos[kl]))
            o.append("    BARRIER(); }")
        for j, l in enumerate(grp):
            o.append("    L[%d] = a%d;" % (l, j))
        o.append("  }")
    o.append("}")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    for P in map(int, sys.argv[1:]):
        with open("kern_p%d.h" % P, "w") as f:
            f.write(gen(P))
