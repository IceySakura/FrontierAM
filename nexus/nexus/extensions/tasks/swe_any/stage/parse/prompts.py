"""Pinned Claude Code prompt for the Parse seed-policy pass.

The agent explores the repo read-only and writes one JSON file to a pinned sandbox
path, which the host downloads, validates and archives. Its job is to classify repo
paths once per repo, so Select never seeds a slice inside generated or vendored code.
"""

from __future__ import annotations

from collections.abc import Sequence


SEED_POLICY_PROMPT_TEMPLATE = """\
You are profiling a repository so a later stage can pick good starting points
for feature extraction.

Repository root (read-only): {working_dir}
Entity graph (read-only): {graph_path}

Directory profile of the graph (entity count / file count, largest first):

{profile}

Your job: decide which paths must NOT be used as a STARTING POINT for feature
extraction. Exclude code that is not hand-written product logic - generated
clients and stubs (OpenAPI / protobuf / thrift / ORM migrations), vendored or
third-party trees, build output, docs and example scaffolding. Read enough of
the actual files to be sure: file headers ("do not edit", "generated by"),
uniform boilerplate across many files, and build configs are the evidence.

Do NOT exclude a path just because it is large, mechanical or test-only.
Excluded code stays visible to the later stage as context - you are only saying
"do not START here". When in doubt, leave it in.

WRITE exactly one JSON object to this path (create parent dirs if needed;
overwrite if present):

    {policy_path}

The file must contain ONLY this JSON object (no markdown fences):

{{"exclude_globs": [<repo-relative glob>, ...],
 "exclude_reasons": {{<glob>: <one short sentence>}},
 "notes": <one or two sentences on where the real product logic lives>}}

Globs are matched against repo-relative file paths with ``fnmatch``, where ``*``
also matches ``/`` - so ``pkg/gen/*`` covers the whole subtree. An empty
``exclude_globs`` is a valid answer for a repo that is all hand-written code.
Never exclude the whole repository: your globs are applied as written, so a
sweeping one leaves the later stage nowhere to start.
After writing the file, print a short confirmation to stdout. Do not attempt
network access, modify source files, or run the test suite.
"""


def build_seed_policy_prompt(
    *,
    working_dir: str,
    graph_path: str,
    policy_path: str,
    profile: Sequence[tuple[str, int, int]],
) -> str:
    """Render the Parse seed-policy prompt around a precomputed directory profile.

    The profile keeps the agent from crawling a multi-thousand-node graph just to
    learn the layout; it still reads real files to justify each exclusion.
    """
    lines = [f'{nodes:6d} entities  {files:4d} files  {directory}' for directory, nodes, files in profile]
    return SEED_POLICY_PROMPT_TEMPLATE.format(
        working_dir=working_dir,
        graph_path=graph_path,
        policy_path=policy_path,
        profile='\n'.join(lines) or '(empty graph)',
    )
